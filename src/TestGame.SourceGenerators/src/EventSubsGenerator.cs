using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace TestGame.SourceGenerators;

[Generator]
public class EventSubsGenerator: IIncrementalGenerator {
    private const string EventHandlerAttribute = "TestGame.Api.Event.EventHandlerAttribute";
    private const string EventType = "TestGame.Api.Event.Event";
	
	private static readonly DiagnosticDescriptor InvalidHandlerParameters = new(
		"TG0001",
		"Invalid handler parameters",
		"The number of parameters is not equal to 1, or its type does not inherit from TestGame.Api.Event.Event",
		"Usage",
		DiagnosticSeverity.Warning,
		true
	);

    private static readonly DiagnosticDescriptor InvalidHandlerReturnType = new(
        "TG0002",
        "Invalid handler return type",
        "The return type is not System.Threading.Tasks.Task",
        "Usage",
        DiagnosticSeverity.Warning,
        true
    );
    
	public void Initialize(IncrementalGeneratorInitializationContext context) {
		IncrementalValueProvider<ImmutableArray<IMethodSymbol>> methods = context.SyntaxProvider
			.ForAttributeWithMetadataName<IMethodSymbol>(
				EventHandlerAttribute,
				static (mode, _) => mode is MethodDeclarationSyntax,
				static (context, _) => (IMethodSymbol) context.TargetSymbol
			)
			.Collect();
        
		context.RegisterSourceOutput(
			context.CompilationProvider.Combine(methods),
			(context, data) => RegisterSource(context, data.Left, data.Right)
		);
	}

	private static void RegisterSource(SourceProductionContext context, Compilation compilation, ImmutableArray<IMethodSymbol> methods) {
		ITypeSymbol? eventType = compilation.GetTypeByMetadataName(EventType);
        if (eventType is null || methods.Length == 0)
            return;
		
        Dictionary<ITypeSymbol, IList<IMethodSymbol>> grouped = new(SymbolEqualityComparer.Default);
		foreach (IMethodSymbol method in methods) {
            
            
			if (method.Parameters.Length != 1) {
				context.ReportDiagnostic(
					Diagnostic.Create(
						InvalidHandlerParameters,
						method.Locations.FirstOrDefault()
					)
				);
                continue;
            }
			ITypeSymbol parameterType = method.Parameters[0].Type;

            if (!parameterType.IsInheritsFrom(eventType)) {
                context.ReportDiagnostic(
                    Diagnostic.Create(
                        InvalidHandlerParameters,
                        method.Locations.FirstOrDefault()
                    )
                );
                continue;
            }

            if (!grouped.ContainsKey(parameterType))
				grouped[parameterType] = new List<IMethodSymbol>();
			grouped[parameterType].Add(method);
		}
		
		context.AddSource(
			"GeneratedEventSubs.generated.cs",
			GenerateFileSource(grouped)
		);
	}

	private static string GenerateFileSource(IDictionary<ITypeSymbol, IList<IMethodSymbol>> methods) {
		StringBuilder builder = new StringBuilder()
			.AppendLine("// <auto-generated />")
			.AppendLine()
			.AppendLine("namespace TestGame.Api.Generated;")
			.AppendLine()
			.AppendLine("using TestGame.Api.Event;")
			.AppendLine("using System;")
			.AppendLine("using System.Collections.Generic;")
			.AppendLine("using System.Collections.Frozen;")
			.AppendLine("using System.Threading.Tasks;")
			.AppendLine()
			.AppendLine("public static class EventSubs {")
			.Append('\t')
			.AppendLine("public static readonly IReadOnlyDictionary<Type, IReadOnlyCollection<Func<Event, Task>>> Subs = new Dictionary<Type, IReadOnlyCollection<Func<Event, Task>>>() {");

		foreach (KeyValuePair<ITypeSymbol, IList<IMethodSymbol>> method in methods) {
			builder
				.Append('\t', 2)
				.Append("[typeof(")
				.Append(method.Key.ToDisplayString())
				.AppendLine(")] = [");
			foreach (IMethodSymbol symbol in method.Value) 
				builder
					.Append('\t', 3)
					.Append("@event => ")
					.Append(symbol.ContainingType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat))
					.Append('.')
					.Append(symbol.Name)
					.AppendLine("(")
					.Append('\t', 4)
					.Append('(')
					.Append(method.Key.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat))
					.AppendLine(") @event")
					.Append('\t', 3)
					.AppendLine("),");
			builder
				.Append('\t', 2)
				.AppendLine("],");
		}
		
		builder
			.AppendLine("\t}.ToFrozenDictionary();")
			.AppendLine("}");
		return builder.ToString();
	}
}
